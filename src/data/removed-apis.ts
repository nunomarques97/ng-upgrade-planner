// Written by hand from the official sources cited on every entry; each source was read on the
// retrieval date below. Only changes a source scan can find are entries: behaviour, timing and
// typing changes, instance members and packages outside @angular/* are listed in
// REMOVED_API_EXCLUDED with the reason. Text is plain ASCII.
