const ANGULAR_COMMIT = 'c0dc8c4bbeea70879aef54e9fcc7888359dfd1a5';
const CLI_COMMIT = 'f61de6620271d71bb7fc051d0ea03426bfa2af5b';
const UPDATE_GUIDE_COMMIT = '647bf8e1436d5479b475d6364c427662586e4c88';

/** Release dates of the major releases, as in the CHANGELOG headings. */
const RELEASE_DATES: Readonly<Record<number, string>> = {
  9: '2020-02-06',
  10: '2020-06-24',
  11: '2020-11-11',
  12: '2021-05-12',
  13: '2021-11-03',
  14: '2022-06-02',
  15: '2022-11-16',
  16: '2023-05-03',
  17: '2023-11-08',
  18: '2024-05-22',
  19: '2024-11-19',
  20: '2025-05-28',
  21: '2025-11-19',
  22: '2026-06-03',
};

function headingAnchor(major: number): string {
  const date = RELEASE_DATES[major];
  if (date === undefined) throw new Error(`No release date recorded for Angular ${major}`);
  return `${major}00-${date}`;
}

/** Breaking changes of an Angular major in the framework CHANGELOG (13 and older are archived). */
function changelog(major: number): RemovedApiSource {
  const file = major <= 13 ? 'CHANGELOG_ARCHIVE.md' : 'CHANGELOG.md';
  return {
    url: `https://github.com/angular/angular/blob/${ANGULAR_COMMIT}/${file}#${headingAnchor(major)}`,
    title: `Angular CHANGELOG, ${major}.0.0 breaking changes`,
  };
}

/** Breaking changes of an Angular major in the Angular CLI CHANGELOG. */
function cliChangelog(major: number): RemovedApiSource {
  return {
    url: `https://github.com/angular/angular-cli/blob/${CLI_COMMIT}/CHANGELOG.md#${headingAnchor(major)}`,
    title: `Angular CLI CHANGELOG, ${major}.0.0 breaking changes`,
  };
}

/** The data file behind angular.dev/update-guide, at the commit bundled in update-steps.ts. */
function updateGuide(step: string): RemovedApiSource {
  return {
    url: `https://github.com/angular/angular/blob/${UPDATE_GUIDE_COMMIT}/adev/src/app/features/update/recommendations.ts`,
    title: `Angular update guide data, step "${step}"`,
  };
}

/** The `ng update` migrations that @angular/core ships in a release. */
function coreMigrations(major: number): RemovedApiSource {
  const tag = major >= 22 ? `v${major}.0.0` : `${major}.0.0`;
  return {
    url: `https://github.com/angular/angular/blob/${tag}/packages/core/schematics/migrations.json`,
    title: `@angular/core ${major}.0.0 ng update migrations`,
  };
}

/** The `ng update` migrations that @angular/cli ships in a release. */
function cliMigrations(major: number): RemovedApiSource {
  return {
    url: `https://github.com/angular/angular-cli/blob/${major}.0.0/packages/schematics/angular/migrations/migration-collection.json`,
    title: `@angular/cli ${major}.0.0 ng update migrations`,
  };
}

/** The public exports of @angular/platform-browser at a release tag. */
function hammerExports(major: number): RemovedApiSource {
  const tag = major >= 22 ? `v${major}.0.0` : `${major}.0.0`;
  return {
    url: `https://github.com/angular/angular/blob/${tag}/packages/platform-browser/src/platform-browser.ts`,
    title: `@angular/platform-browser ${major}.0.0 public exports`,
  };
}

